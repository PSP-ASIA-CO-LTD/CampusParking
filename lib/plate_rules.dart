// กฎการอ่านทะเบียนรถ
//
// ไฟล์นี้เก็บกฎที่ "ดูจากตัวทะเบียนแล้วรู้ได้เลย" โดยไม่ต้องถามเจ้าหน้าที่
// แยกเป็นไฟล์ของตัวเอง เพราะไม่ยุ่งกับการรับ input และไม่พิมพ์อะไรออกหน้าจอ
// จึงเขียน unit test ครอบได้ครบทุกกรณี โดยไม่ต้องรันโปรแกรมจริง

// รายชื่อตัวอักษรที่นับว่าเป็น "ตัวเลข" เอาไว้ใช้ตรวจทีละตัว
const String _digits = '0123456789';

// ตัวอักษรตัวนี้เป็นตัวเลขหรือเปล่า
bool _isDigit(String character) {
  return _digits.contains(character);
}

// ทะเบียนแบบไหนถือว่าเป็นสมาชิก
//
// กติกาคือ ต้องขึ้นต้นด้วยตัวเลข (กี่ตัวก็ได้) แล้วตามด้วยขีดทันที
//
//   12-ABC    เป็นสมาชิก    เลข 2 ตัว แล้วเจอขีด
//   123-ABC   เป็นสมาชิก    เลข 3 ตัว แล้วเจอขีด
//   12-       ไม่ใช่        มีขีดแล้ว แต่ไม่มีอะไรต่อท้าย
//   1234      ไม่ใช่        มีแต่เลข ไม่มีขีด
//   12ABC     ไม่ใช่        ถัดจากเลขเป็นตัวอักษร ไม่ใช่ขีด
//   AB-123    ไม่ใช่        ขึ้นต้นด้วยตัวอักษร
//   -123      ไม่ใช่        ไม่มีเลขนำหน้าขีดเลย
bool isMemberPlate(String plate) {
  // ตัดช่องว่างหน้าหลังทิ้งก่อน เผื่อเจ้าหน้าที่เผลอเคาะ space ติดมา
  String input = plate.trim();

  // นับว่ามีตัวเลขนำหน้าอยู่กี่ตัว
  // เริ่มจากตัวซ้ายสุด แล้วเดินไปทางขวาเรื่อย ๆ จนกว่าจะเจอตัวที่ไม่ใช่ตัวเลข
  //
  //   ทะเบียน   1  2  -  A  B  C
  //   ตำแหน่ง   0  1  2  3  4  5
  //                   ^
  //                   หยุดตรงนี้ เพราะ '-' ไม่ใช่ตัวเลข ได้ index = 2
  int index = 0;
  while (index < input.length && _isDigit(input[index])) {
    index++;
  }

  // ถึงตรงนี้ index คือตำแหน่งของตัวแรกที่ไม่ใช่ตัวเลข
  // จะเป็นสมาชิกได้ ต้องผ่านครบทั้ง 4 ข้อ

  // ข้อ 1 ต้องมีตัวเลขนำหน้าอย่างน้อย 1 ตัว
  //       ถ้า index ยังเป็น 0 แปลว่าตัวแรกสุดไม่ใช่ตัวเลข
  if (index == 0) {
    return false;
  }

  // ข้อ 2 ต้องมีอะไรเหลืออยู่หลังกลุ่มตัวเลข
  //       ถ้าเดินจนสุดสตริงแล้ว แปลว่าทั้งทะเบียนเป็นตัวเลขล้วน ไม่มีขีด
  if (index == input.length) {
    return false;
  }

  // ข้อ 3 ตัวที่ทำให้หยุดเดิน ต้องเป็นเครื่องหมายขีด
  if (input[index] != '-') {
    return false;
  }

  // ข้อ 4 หลังขีดต้องมีตัวอักษรต่ออีกอย่างน้อย 1 ตัว
  //       ทะเบียนอย่าง "12-" ไม่ใช่ทะเบียนรถจริง ถ้าปล่อยผ่าน
  //       ใครพิมพ์ "12-" ก็จะได้ส่วนลดสมาชิกไปฟรี ๆ
  return index + 1 < input.length;
}
